"""
phase1_5_analysis.py
====================
Runs Phases 1 through 5 of the SCoT diagnostics for Llama-3.3-70b-instruct.
Uses the parsed log records generated by phase0.

Outputs (written to analysis_scot_diagnostics/):
  - per_query_flags.csv
  - stage_flips.csv
  - oracle_vs_selected.csv
  - loss_attribution.csv
  - REPORT.md
"""

import sys, csv, json, pickle, re, sqlite3, time
from collections import Counter
from pathlib import Path

ROOT      = Path(__file__).resolve().parent.parent
RUN_DIR   = ROOT / "runs" / "spider_full"
OUT_DIR   = Path(__file__).resolve().parent
DB_DIR    = ROOT / "data" / "spider" / "database"

BACKENDS = [
    "meta-llama_llama-3.3-70b-instruct",
    "anthropic_claude-haiku-4.5",
    "google_gemini-2.5-flash",
    "openai_gpt-4o-mini"
]

def get_backend_name(b):
    if "llama" in b: return "llama"
    if "haiku" in b: return "haiku"
    if "gemini" in b: return "gemini"
    return "gpt4o"

QUERY_TIMEOUT = 5

# --- Utils ---
def norm_cell(x) -> str:
    try:
        if x is None: return ""
        s = str(x).strip()
        try: float(s); return s
        except ValueError: return s.lower()
    except Exception: return str(x)

def run_query(db_path: Path, sql: str, timeout=QUERY_TIMEOUT):
    try:
        con = sqlite3.connect(str(db_path))
        _start = time.monotonic()
        def _chk(): return 1 if time.monotonic() - _start > timeout else 0
        con.set_progress_handler(_chk, 1000)
        cur = con.cursor()
        cur.execute(sql)
        rows = cur.fetchall()
        cur.close(); con.close()
        norm = [tuple(norm_cell(c) for c in r) for r in rows]
        norm.sort()
        return True, norm, None
    except Exception as e:
        return False, None, str(e)

