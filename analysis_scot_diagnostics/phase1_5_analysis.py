def load_data(backend):
    test_data = json.loads((RUN_DIR / "my_test_set.json").read_text(encoding="utf-8"))
    bname = get_backend_name(backend)
    with (OUT_DIR / f"parsed_debug_{bname}.pkl").open("rb") as f:
        records = pickle.load(f)
    
    # Load gold SQL and EX status for baseline
    qdic_csv = RUN_DIR / f"eval_report__predicted_qd_intercol_models_{backend}.csv"
    qdic_rows = list(csv.DictReader(qdic_csv.open(encoding="utf-8")))
    
    scot_csv = RUN_DIR / f"eval_report__predicted_scot_models_{backend}.csv"
    scot_rows = list(csv.DictReader(scot_csv.open(encoding="utf-8")))
                 
    return test_data, records, qdic_rows, scot_rows

def main():
    with open(OUT_DIR / "REPORT_ALL.md", "w", encoding="utf-8") as f_report:
        f_report.write("# SCoT Diagnostics Report (All Backends)\n\n")
        all_loss_causes = {}
        
        for backend in BACKENDS:
            bname = get_backend_name(backend)
            print(f"Processing backend: {bname}...")
            test_data, records, qdic_rows, scot_rows = load_data(backend)
            test_by_idx = {ex["idx"]: ex for ex in test_data}
            total_q = len(test_data)
    
            # --- PHASE 1: Stage-level failure rates ---
            p1 = {
                "plan_missing": 0, "plan_unparseable": 0, "plan_check_unparseable": 0,
                "plan_changed": 0, "plan_changed_ex_correct": 0, "plan_unchanged_ex_correct": 0,
                "cand_count": [], "cands_0": 0, "cands_lt4": 0, "cands_dups": 0,
                "raw_cand_exec_ok": 0, "raw_cand_total": 0,
                "stg7_filtered_all": 0
            }
            
            # --- PHASE 2: Oracle vs Selected ---
            p2 = {
                "selected_correct": 0, "oracle_raw": 0, "oracle_post": 0, "oracle_stg7": 0,
                "ranking_gap_queries": 0,
                "cand_types": {"SCoT-Native": [0,0,0], "QD-InterCol": [0,0,0], "Standard": [0,0,0], "INTERSECT": [0,0,0], "EXCEPT": [0,0,0], "UNION": [0,0,0]} # [total, selected, selected_correct]
            }
            
            # --- PHASE 3: Repair regression ---
            # We will compute flips between CANDS (pre-canon/repair) and CANON_CANDS
            p3 = {"harm": 0, "benefit": 0, "harm_examples": []}
            
            # --- PHASE 4: Loss attribution ---
            loss_causes = Counter()
            loss_examples = []
            
            per_query = []
            
            # Deduplicate records (keep last occurrence)
            rec_by_idx = {}
            for r in records:
                # The log printed 'IDX i' where i is 1-indexed enumerate from test_data
                rec_by_idx[r["idx"]] = r
                
            for i_idx, ex in enumerate(test_data):
                # Log idx is 1-indexed
                log_idx = i_idx + 1
                if log_idx not in rec_by_idx:
                    print(f"WARNING: Missing log for IDX {log_idx} in {bname}")
                    continue
                    
                rec = rec_by_idx[log_idx]
                db_id = rec["db_id"]
                idx = ex["idx"]  # Real dataset idx
                db_path = DB_DIR / db_id / f"{db_id}.sqlite"
                
                # Gold execution
                gold_ok, gold_res, _ = run_query(db_path, ex["gold_query"])
                
                # P1: Plan
                plan = rec.get("plan") or ""
                is_plan_ok = "SCoT-Plan:" in plan and "FROM:" in plan and "SELECT:" in plan
                if not plan: p1["plan_missing"] += 1
                elif not is_plan_ok: p1["plan_unparseable"] += 1
                
                checked = rec.get("checked") or ""
                is_chk_ok = "SCoT-Plan:" in checked and "FROM:" in checked and "SELECT:" in checked
                if not is_chk_ok: p1["plan_check_unparseable"] += 1
                
                changed = (plan != checked)
                if changed: p1["plan_changed"] += 1
                
                # P1: Cands
                raw_texts = rec.get("raw_sql_texts") or []
                cands = rec.get("cands") or []
                canon_cands = rec.get("canon_cands") or []
                
                n_cands = len(cands)
                p1["cand_count"].append(n_cands)
                if n_cands == 0: p1["cands_0"] += 1
                elif n_cands < 4: p1["cands_lt4"] += 1
                
                if n_cands > len(set([c[1] for c in cands])): p1["cands_dups"] += 1
                
                # Oracles
                any_raw_corr = False
                any_post_corr = False
                
                # Evaluate CANDS
                cands_eval = []
                for ctype, csql in cands:
                    p1["raw_cand_total"] += 1
                    cok, cres, _ = run_query(db_path, csql)
                    if cok: p1["raw_cand_exec_ok"] += 1
                    c_corr = (cok and gold_ok and cres == gold_res)
                    if c_corr: any_raw_corr = True
                    cands_eval.append((ctype, csql, c_corr))
                    
                # Evaluate CANON_CANDS (Post-repair)
                canon_eval = []
                # Need types for canon cands. Assume zip aligns.
                for csql in canon_cands:
                    cok, cres, _ = run_query(db_path, csql)
                    c_corr = (cok and gold_ok and cres == gold_res)
                    if c_corr: any_post_corr = True
                    canon_eval.append((csql, c_corr))
                    
                # P3: Repair flips
                for i, (ctype, csql, c_corr) in enumerate(cands_eval):
                    if i < len(canon_eval):
                        pcsql, pc_corr = canon_eval[i]
                        if c_corr and not pc_corr:
                            p3["harm"] += 1
                            if len(p3["harm_examples"]) < 10:
                                p3["harm_examples"].append({
                                    "idx": idx, "type": ctype, "before": csql, "after": pcsql, "gold": ex["gold_query"]
                                })
                        elif not c_corr and pc_corr:
                            p3["benefit"] += 1
                
                # Selected accuracy
                final_sql = rec.get("final_sql", "")
                # The scot_csv 'match' has the actual final execution
                is_scot_correct = scot_rows[i_idx]["match"].strip().lower() == "true"
                
                if i_idx % 100 == 0:
                    print(f"Processed {i_idx}/1034 queries...")
                
                if is_scot_correct: p2["selected_correct"] += 1
                if any_raw_corr: p2["oracle_raw"] += 1
                if any_post_corr: p2["oracle_post"] += 1
                
                if changed and is_scot_correct: p1["plan_changed_ex_correct"] += 1
                elif not changed and is_scot_correct: p1["plan_unchanged_ex_correct"] += 1
                
                if not canon_cands: p1["stg7_filtered_all"] += 1
                
                # Ranking gap
                if any_post_corr and not is_scot_correct:
                    p2["ranking_gap_queries"] += 1
                    
                # P4: Loss attribution (SCoT loses, QD-InterCol wins)
                is_qdic_correct = qdic_rows[i_idx]["match"].strip().lower() == "true"
                loss_cause = None
                if is_qdic_correct and not is_scot_correct:
                    if not is_plan_ok or not cands or not canon_cands:
                        loss_cause = "Pipeline Failure (empty/unparseable)"
                    elif any_raw_corr and not any_post_corr:
                        loss_cause = "Repair Damage (Stages 4-6 broke correct cand)"
                    elif any_post_corr:
                        loss_cause = "Ranking Error (Stage 7 selected wrong cand)"
                    elif not any_raw_corr:
                        loss_cause = "Generation Failure (No LLM cand correct)"
                    else:
                        loss_cause = "Other"
                        
                    loss_causes[loss_cause] += 1
                    if len(loss_examples) < 25:
                        loss_examples.append({"idx": idx, "cause": loss_cause, "gold": ex["gold_query"], "final": final_sql})
                        
                per_query.append({
                    "idx": idx,
                    "plan_ok": is_plan_ok,
                    "chk_changed": changed,
                    "n_cands": n_cands,
                    "oracle_raw": any_raw_corr,
                    "oracle_post": any_post_corr,
                    "scot_correct": is_scot_correct,
                    "qdic_correct": is_qdic_correct,
                    "loss_cause": loss_cause
                })
        
            # Write Outputs to markdown
            f_report.write(f"## Backend: {bname}\n\n")
            
            f_report.write("### Phase 1: Stage-Level Failure Rates\n")
            f_report.write(f"- Plan missing/unparseable: {p1['plan_unparseable'] + p1['plan_missing']} / {total_q}\n")
            f_report.write(f"- Plan-check unparseable: {p1['plan_check_unparseable']} / {total_q}\n")
            f_report.write(f"- Plans changed by check: {p1['plan_changed']} (EX if changed: {p1['plan_changed_ex_correct']/(p1['plan_changed'] or 1)*100:.1f}%; if unchanged: {p1['plan_unchanged_ex_correct']/(total_q - p1['plan_changed'] or 1)*100:.1f}%)\n")
            f_report.write(f"- Queries with 0 candidates: {p1['cands_0']}\n")
            f_report.write(f"- Queries with < 4 candidates: {p1['cands_lt4']}\n")
            f_report.write(f"- Queries where Stage 7 filtered ALL candidates: {p1['stg7_filtered_all']}\n\n")
            
            f_report.write("### Phase 2: Oracle vs Selected Accuracy\n")
            f_report.write(f"- SCoT Selected Accuracy: {p2['selected_correct']/total_q*100:.2f}%\n")
            f_report.write(f"- Oracle (Raw Cands): {p2['oracle_raw']/total_q*100:.2f}%\n")
            f_report.write(f"- Oracle (Post-Repair): {p2['oracle_post']/total_q*100:.2f}%\n")
            f_report.write(f"- Ranking Gap (Oracle Post-Repair minus Selected): {(p2['oracle_post'] - p2['selected_correct'])/total_q*100:.2f}pp ({p2['ranking_gap_queries']} queries)\n\n")
            
            f_report.write("### Phase 3: Repair Regression (Stages 4-6)\n")
            f_report.write(f"- Harmful flips (Correct -> Incorrect): {p3['harm']}\n")
            f_report.write(f"- Beneficial flips (Incorrect -> Correct): {p3['benefit']}\n")
            f_report.write(f"- Net effect: {p3['benefit'] - p3['harm']} queries\n\n")
            
            f_report.write("### Phase 4: Loss Attribution (vs QD+InterCol)\n")
            f_report.write("For queries where QD+InterCol was correct but SCoT failed:\n")
            for cause, count in loss_causes.most_common():
                f_report.write(f"- **{cause}**: {count}\n")
            f_report.write("\n---\n\n")
            
            all_loss_causes[bname] = loss_causes
            
            # Save per-query flags per backend
            with open(OUT_DIR / f"per_query_flags_{bname}.csv", "w", newline="", encoding="utf-8") as f_csv:
                w = csv.DictWriter(f_csv, fieldnames=per_query[0].keys())
                w.writeheader()
                w.writerows(per_query)

        # Cross-backend comparison
        f_report.write("## Phase 5: Cross-Backend Loss Analysis\n\n")
        f_report.write("| Backend | Pipeline Failure | Generation Failure | Repair Damage | Ranking Error |\n")
        f_report.write("|:---|:---:|:---:|:---:|:---:|\n")
        for bname in ["llama", "haiku", "gemini", "gpt4o"]:
            c = all_loss_causes.get(bname, Counter())
            pipe = c.get("Pipeline Failure (empty/unparseable)", 0)
            gen = c.get("Generation Failure (No LLM cand correct)", 0)
            rep = c.get("Repair Damage (Stages 4-6 broke correct cand)", 0)
            rank = c.get("Ranking Error (Stage 7 selected wrong cand)", 0)
            f_report.write(f"| {bname} | {pipe} | {gen} | {rep} | {rank} |\n")
            
        print("[OK] All backends processed successfully.")

if __name__ == '__main__':
    main()
